/**
 * 座標が県の想定範囲を外れていれば true。県が未知なら false（判定しない）。
 *
 * `isIsland` に true を渡すと**矩形検査をしない**（島嶼は本土の矩形に収まらないため）。
 * 上の東京のコメントを参照。**スキップした分は verify-coords-gsi.js の
 * 逆ジオコーディングによる市区町村一致で見る**という取り決めになっている。
 *
 * 呼び出し側はレコードの `isIsland` をそのまま渡すこと。**渡し忘れると島嶼が
 * 範囲外エラーになる**（3箇所ある: validate-data.js / audit-names.js / check-coords.js）。
 */
function isOutOfBounds(prefecture, lat, lng, isIsland) {
  if (isIsland === true) return false;
  const b = PREFECTURE_BOUNDS[prefecture];
  if (!b) return false;
  return lat < b.latMin || lat > b.latMax || lng < b.lngMin || lng > b.lngMax;
}

/** 「lat 35.10〜35.68 / lng 138.90〜139.80」形式の説明文字列。 */
function describeBounds(prefecture) {
  const b = PREFECTURE_BOUNDS[prefecture];
  if (!b) return '(範囲未定義)';
  return `lat ${b.latMin}〜${b.latMax} / lng ${b.lngMin}〜${b.lngMax}`;
}

module.exports = { PREFECTURE_BOUNDS, isOutOfBounds, describeBounds };
